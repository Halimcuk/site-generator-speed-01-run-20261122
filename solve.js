// A fast, dependency-free reimplementation of makefun-site 1.0.0's build (the
// reference program of site-generator-speed-01), written from scratch in this
// session from the reference's stated rules and its code. run(input) returns
// exactly the output tree makefun-site 1.0.0 returns for the same input.
//
// Speed comes from removing the reference's per-character work: the inline
// renderer scans plain runs in bulk instead of escaping one character at a
// time, the Markdown lexer and renderer are one fused pass with no token
// objects, slugify is cached with an ASCII fast path, and each template is
// compiled once per build into a plain JavaScript function (with an
// interpreter fallback if compilation ever fails). No semantics are changed:
// every branch below mirrors the reference's, in its order.

